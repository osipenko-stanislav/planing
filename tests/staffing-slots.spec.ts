import { test, expect } from '@playwright/test';
test.use({ channel: 'chrome' });
test('course plan creates slots; adding and cancelling a person updates vacancies', async ({ page }) => {
  await page.goto('/courses/financial-math');
  await page.getByRole('link', { name: 'Редактировать курс', exact: true }).click();
  await page.getByLabel('Лид курса', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page).toHaveURL(/\/courses\/financial-math$/);
  await page.getByRole('link',{name:'Кандидат не указан',exact:true}).first().click();
  await page.getByRole('link',{name:'Редактировать данные'}).click();
  await page.getByLabel('Карточка кандидата в Candy *',{exact:true}).fill('https://candy.example/candidates/2');
  await page.getByLabel('Jira-таска по кандидату',{exact:true}).fill('https://jira.example/browse/DEMO-8');
  await page.getByLabel('Заметки',{exact:true}).focus();
  await expect(page.getByLabel('Статус найма',{exact:true})).toHaveValue('Оформление отменено');
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.goto('/courses/financial-math');
  await expect(page.locator('.hire-cancelled')).toHaveText('Оформление отменено');
  await expect(page.locator('.vacancy-row')).toHaveCount(1);
  await page.reload();
  await expect(page.locator('.vacancy-row')).toHaveCount(1);
});
test('completed role has a checkmark and no vacancy; zero-plan empty roles are hidden', async ({ page }) => {
  await page.goto('/courses/financial-math');
  await page.getByRole('link', { name: 'Редактировать курс', exact: true }).click();
  await page.getByLabel('Лектор', { exact: true }).fill('1');
  await page.getByLabel('Лид курса', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page).toHaveURL(/\/courses\/financial-math$/);
  await expect(page.locator('.role-group').filter({ has: page.getByRole('button', { name: 'Комплект Лектор', exact: true }) }).locator('.vacancy-row')).toHaveCount(0);
  await expect(page.locator('.role-row').filter({ hasText: 'Лид курса' })).toHaveCount(0);
  await expect(page.locator('.role-indicator[aria-label="Комплект"]')).toHaveCount(1);
});
