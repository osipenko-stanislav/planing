import { test, expect } from '@playwright/test';
test.use({ channel: 'chrome' });
test('course plan creates slots; adding and cancelling a person updates vacancies', async ({ page }) => {
  await page.goto('/courses/financial-math');
  await page.getByRole('link', { name: 'Редактировать курс', exact: true }).click();
  await page.getByLabel('Лид курса', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page).toHaveURL(/\/courses\/financial-math$/);
  const vacancies = await page.locator('.vacancy-row').count();
  await page.getByRole('link', { name: 'Заполнить вакансию: Лид курса, 1', exact: true }).click();
  await page.getByLabel('Кандидат', { exact: true }).fill('Проверка Свободного Места');
  await page.getByRole('button', { name: 'Выбери дату выхода' }).click();
  await page.locator('.calendar-grid').getByRole('button', { name: '18', exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Проверка Свободного Места', exact: true })).toBeVisible();
  await page.locator('.breadcrumbs').getByRole('link', { name: 'Финансовая математика' }).click();
  await expect(page.locator('.vacancy-row')).toHaveCount(vacancies - 1);
  const person = page.locator('.person-link').filter({ hasText: 'Проверка Свободного Места' });
  await expect(person.locator('..').locator('.start-date')).toBeVisible();
  await person.click();
  await page.getByRole('link', { name: 'Редактировать данные' }).click();
  await page.getByLabel('Статус найма', { exact: true }).click();
  await page.getByRole('option', { name: 'Отмена оформления', exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await page.locator('.breadcrumbs').getByRole('link', { name: 'Финансовая математика' }).click();
  await expect(page.locator('.vacancy-row')).toHaveCount(vacancies);
  await expect(page.locator('.hire-cancelled')).toHaveText('Отмена оформления');
  await page.reload();
  await expect(page.locator('.vacancy-row')).toHaveCount(vacancies);
});
test('completed role has a checkmark and no vacancy; zero-plan empty roles are hidden', async ({ page }) => {
  await page.goto('/courses/financial-math');
  await page.getByRole('link', { name: 'Редактировать курс', exact: true }).click();
  await page.getByLabel('Лектор', { exact: true }).fill('1');
  await page.getByLabel('Лид курса', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page).toHaveURL(/\/courses\/financial-math$/);
  await expect(page.locator('.role-group').filter({ has: page.getByRole('button', { name: 'Комплект Лектор', exact: true }) }).locator('.vacancy-row')).toHaveCount(0);
  await expect(page.locator('.role-row').filter({ hasText: 'Лид курса' })).toHaveCount(0);
  await expect(page.locator('.role-indicator[aria-label="Комплект"]')).toHaveCount(1);
});
